const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('supabase-app/app.js','utf8');
const storage = {};
const ctx = { localStorage: { getItem: k => storage[k], setItem: (k,v) => storage[k]=v },
  reconciliationAccountKind: () => 'Bank Statement', bankTransactionBank: (r,b) => r.bank_account===b,
  bankBookDisplayReference: r=>r.reference, bankPayeeName: r=>r.description };
vm.createContext(ctx);
vm.runInContext(source.slice(source.indexOf('const BANK_RECONCILIATION_MARKS_KEY'), source.indexOf('function bindBankReconciliationMarks')),ctx);
vm.runInContext(source.slice(source.indexOf('function buildBankStatement('), source.indexOf('\nfunction bankBookDisplayReference')),ctx);
const bank='FHB Checking';
const row=(reference,debit,credit,date='2026-08-20',source='Check Run')=>({reference,debit,credit,posting_date:date,account:bank,source});
const gl=[row('CHECK',0,100),row('DEP',70,0,'2026-08-21','Sales Order Deposit'),row('PAY',0,20,'2026-08-22','Transfer')];
const banks=[{bank_account:bank,reference:'FEE',tx_date:'2026-08-23',amount:-5}];
const report=(month)=>ctx.buildBankStatement(gl,banks,bank,`2026-${month}-01`,`2026-${month}-30`,0);
let sept=report('09');
assert.equal(sept.outstandingChecksTotal,120);
assert.equal(sept.depositsInTransitTotal,70);
assert.equal(sept.otherBankItemsTotal,-5);
assert.equal(sept.bookEnding,-50);
assert.equal(sept.checksReleasedTotal,0);
for(const r of [...sept.outstandingChecks,...sept.depositsInTransit,...sept.otherBankItems]) ctx.setBankReconciliationMark(r._reconciliationKey,false);
assert.equal(report('09').outstandingChecksTotal,0);
assert.equal(report('10').depositsInTransitTotal,0);
assert.equal(report('10').otherBankItemsTotal,0);
assert.equal(report('08').outstandingChecksTotal,120);
assert.equal(report('09').clearedItems.length,4);
assert.equal(report('08').clearedItems.length,0);
assert.equal(report('10').clearedItems.length,0);
const restore=report('09').clearedItems.find(row=>row.num==='CHECK');
ctx.setBankReconciliationMark(restore._reconciliationKey,true);
assert.equal(report('09').outstandingChecksTotal,100);
assert.equal(report('10').outstandingChecksTotal,100);
assert.equal(report('09').clearedItems.length,3);
ctx.setBankReconciliationMark(restore._reconciliationKey,false);
gl.push(row('M10000',1102,0,'2026-09-09','Sales Order Deposit'),row('M10000-REV',0,1102,'2026-09-10','Sales Order Deposit Reversal'));
assert.equal(report('09').depositsInTransitTotal,0);
assert.equal(report('09').outstandingChecksTotal,0);
assert.equal(report('09').bookEnding,-50);
assert.equal(report('09').otherReceipts.length,0);
assert.equal(report('09').otherPayments.length,0);
assert.equal(report('09').otherReceiptsTotal,0);
assert.equal(report('09').otherPaymentsTotal,0);
const beforeReversal = ctx.buildBankStatement(gl,banks,bank,'2026-09-01','2026-09-09',0);
assert.equal(beforeReversal.otherReceiptsTotal,1102);
gl.push(row('CURRENT',25,0,'2026-09-15','Sales Order Deposit'));
const current=report('09').depositsInTransit.find(r=>r.num==='CURRENT');
ctx.setBankReconciliationMark(current._reconciliationKey,false);
assert.ok(!report('09').clearedItems.some(r=>r.num==='CURRENT'));
assert.ok(report('09').otherReceipts.some(r=>r.num==='CURRENT'));
assert.ok(!report('10').clearedItems.some(r=>r.num==='CURRENT'));
gl.pop();
gl.push(row('ALREADY-CLEARED',0,50,'2026-08-17'));
const already=report('08').outstandingChecks.find(r=>r.num==='ALREADY-CLEARED');
ctx.setBankReconciliationMark(already._reconciliationKey,false);
assert.ok(!report('09').clearedItems.some(r=>r.num==='ALREADY-CLEARED'));
gl.pop();
gl.push(row('PARTIAL',100,0,'2026-09-11','Sales Order Deposit'),row('PARTIAL-REV',0,40,'2026-09-12','Sales Order Deposit Reversal'));
assert.equal(report('09').otherReceiptsTotal,100);
assert.equal(report('09').otherPaymentsTotal,40);
console.log('PASS: all categories carry over; later clearing preserves prior months; reversal nets out; book activity not duplicated.');
