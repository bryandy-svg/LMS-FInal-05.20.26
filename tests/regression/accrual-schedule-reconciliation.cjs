const assert=require('node:assert/strict'),vm=require('node:vm');
const {functions}=require('../source.cjs');
const c=vm.createContext({roundCurrency:n=>Math.round(n*100)/100});
vm.runInContext(functions(['balanceSheetScheduleReceiptPo','landedCostScheduleBundleMap','balanceSheetScheduleReference','balanceSheetScheduleRows','assertScheduleAccrualCoverage','assertWorkOrderCostCoverage']),c);
const account='Landed Cost Accrual';
const receipt={gr_no:'GR-1',po_no:'PO-1'};
const credit={account,reference:'GR-1',source:'Goods Receipt',credit:100,debit:0};
const invoice=(ref,amount,po='PO-1')=>({account,reference:ref,source:'Landed Cost Invoice',description:`Clear landed cost accrual ${po} - Separate AP`,debit:amount,credit:0});
const a=invoice('LC-1',40),b=invoice('LC-2',60);
let map=c.landedCostScheduleBundleMap([a,b]);
assert.equal(map.get('po-1'),'LC-1 / LC-2');
assert.equal(c.landedCostScheduleBundleMap([b,a]).get('po-1'),map.get('po-1'),'mapping must not depend on row order');
const schedule={title:account,normal:'credit',accountPattern:/^Landed Cost Accrual$/};
assert.equal(c.balanceSheetScheduleRows({gl:[credit,a,b],receipts:[receipt]},schedule).length,0,'shared PO clears both invoices');
c.assertScheduleAccrualCoverage([credit,a],[b],[receipt]);
assert.throws(()=>c.assertScheduleAccrualCoverage([credit,a],[invoice('LC-2',61)],[receipt]),/insufficient/);
assert.throws(()=>c.assertScheduleAccrualCoverage([],[a],[receipt]),/insufficient/);
const partsCredit={...credit,account:'Parts Accrual'};
const correction={account:'Parts Accrual',source:'AP Correction',reference:'APADJ-PO-1-123',description:'Supplemental AP correction PO-1 invoice I1',debit:100};
c.assertScheduleAccrualCoverage([partsCredit],[correction],[receipt]);
assert.throws(()=>c.assertScheduleAccrualCoverage([partsCredit],[{...correction,debit:101}],[receipt]),/insufficient/);
const adj={account,reference:'ADJ-1',source:'Schedule Adjustment',description:'Schedule adjustment for LC-1: authorized correction',credit:40,debit:0};
assert.equal(c.balanceSheetScheduleRows({gl:[a,adj],receipts:[]},schedule).length,0,'adjustment keeps original reference');
const wip=[{reference:'W1-PART-a',source:'Work Order Parts',posting_date:'2026-10-07',debit:100,credit:0}];
assert.throws(()=>c.assertWorkOrderCostCoverage(wip,100,'2026-09-30','W1'),/Reconcile/,'future issuance must not support September clearing');
assert.equal(c.assertWorkOrderCostCoverage(wip,100,'2026-10-26','W1'),100);
const returned=[...wip,{posting_date:'2026-10-08',debit:0,credit:100}];
assert.throws(()=>c.assertWorkOrderCostCoverage(returned,100,'2026-10-26','W1'),/Reconcile/,'stale accepted quantity must not release returned WIP');
assert.equal(c.assertWorkOrderCostCoverage(returned,0,'2026-10-26','W1'),0);
const alreadyCleared=[...wip,{reference:'W1',source:'Work Order Invoice Cost',posting_date:'2026-10-08',debit:0,credit:100}];
assert.equal(c.assertWorkOrderCostCoverage(alreadyCleared,100,'2026-10-26','W1'),100,'retry excludes own prior cost');
assert.throws(()=>c.assertWorkOrderCostCoverage(alreadyCleared,100,'2026-10-26','W1R'),/Reconcile/,'unreversed prior invoice cannot clear twice');
const source=functions(['invoiceWorkOrder']);
assert.ok(source.indexOf('await validateWorkOrderCostCoverage')<source.indexOf('const invoicePayload'));
assert.match(functions(['postPurchaseOrderLedger']),/validateScheduleAccrualPosting\(correctionRows\)/);
assert.ok(functions(['postLandedCostInvoiceLedger']).indexOf('validateScheduleAccrualPosting')<functions(['postLandedCostInvoiceLedger']).indexOf('.delete()'));
console.log('Shared-PO matching, dated WIP, returned parts, retry and accrual coverage checks passed');
